import sys; from shortaudio import Mix
m = Mix(sys.argv[1], 25)
m.music("upbeat")
m.ambience("wind", 0, m.mid(0, 1), .04); m.add("pop", m.wt(0, "but how"), .4)
m.add("whoosh", m.mid(0, 1) - .12, .35)
for w in ("twenty", "eight hours", "from december"): m.add("pop", m.wt(1, w), .4)
m.add("whoosh", m.mid(1, 2) - .12, .3)
for i in range(8): m.add("cash", m.at(2, 0) + i * .22, .2)
m.add("ding", m.at(3, .2), .4); m.add("boing", m.at(4, .2), .35); m.add("whoosh", m.mid(4, 5) - .12, .3)
m.add("buzz", m.wt(5, "most of the"), .3); m.add("chime", m.wt(6, "so they"), .3)
m.add("sting", m.at(7, .2), .5)
for i in range(14): m.add("tick", m.at(8, 0) + i * .2, .4)
m.add("thump", m.wt(8, "battery power"), .5); m.add("whoosh", m.mid(8, 9) - .12, .3); m.add("chime", m.wt(9, "and a timer"), .4)
m.write(mvol=.08, svol=.3)
