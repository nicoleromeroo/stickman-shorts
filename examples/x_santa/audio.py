import sys; from shortaudio import Mix
m = Mix(sys.argv[1], 28)
m.music("upbeat")
for i in range(6): m.add("ding", .3 + i * .45, .12)
m.add("pop", m.wt(0, "let's"), .4); m.add("whoosh", m.mid(0, 1) - .12, .35)
for i in range(12): m.add("tick", m.at(1, 0) + i * .12, .3)
m.add("pop", m.at(2, .3), .4); m.add("chime", m.at(3, 0), .3)
m.add("whoosh", m.mid(3, 4) - .12, .3)
for i in range(16): m.add("tick", m.at(4, 0) + i * .1, .35)
m.add("thump", m.at(4, 0) + 1.1, .45); m.add("boing", m.at(5, .2), .35)
m.add("whoosh", m.mid(5, 6) - .12, .4); m.add("whoosh", m.at(6, .3), .4); m.add("thump", m.at(7, 0) + .2, .45)
m.add("whoosh", m.mid(7, 8) - .12, .3)
for i in range(10): m.add("pop", m.at(8, 0) + i * .3, .2)
m.add("chime", m.at(9, .1), .4)
m.write(mvol=.08, svol=.3)
