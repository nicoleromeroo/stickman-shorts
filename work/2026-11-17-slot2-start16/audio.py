import sys; from shortaudio import Mix
m = Mix(sys.argv[1], 11)
m.music("upbeat")
m.add("cash", .15, .4); m.add("pop", m.wt(0, "less than"), .35)
m.add("whoosh", m.mid(0, 1) - .12, .3); m.add("ding", m.wt(1, "sixteen"), .35); m.add("ding", m.wt(1, "twenty six"), .35)
m.add("slide", m.wt(2, "sixty seven"), .35)
m.add("whoosh", m.mid(2, 3) - .12, .3); m.add("clink", m.wt(3, "six thousand"), .4)
m.add("sting", m.at(4, 0), .45)
m.add("whoosh", m.mid(4, 5) - .12, .3); m.add("cash", m.wt(5, "one hundred"), .4)
m.add("cash", m.wt(6, "two hundred"), .5); m.add("shing", m.wt(6, "almost"), .45)
m.add("whoosh", m.mid(6, 7) - .12, .3); m.add("pop", m.wt(7, "ninety"), .45)
m.add("pdown", m.wt(8, "down"), .3)
m.add("chime", m.wt(9, "time beats"), .45)
m.write(mvol=.08, svol=.3)
