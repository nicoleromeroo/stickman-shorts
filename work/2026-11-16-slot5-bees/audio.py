import sys; from shortaudio import Mix
m = Mix(sys.argv[1], 6)
m.music("upbeat")
m.add("pdown", .15, .45); m.add("buzz", .3, .25); m.add("pop", m.wt(0, "is gone"), .4)
m.add("ding", m.wt(1, "nice"), .4); m.add("sting", m.wt(1, "but one snack"), .35)
m.add("whoosh", m.mid(1, 2) - .12, .3); m.steps(m.at(2, 0), 4, .3, .25); m.add("boing", m.wt(2, "something"), .35)
m.add("whoosh", m.mid(2, 3) - .12, .3)
for k in range(4): m.add("pop", m.at(3, 0) + .25 * k, .35)
m.add("pop", m.at(4, .15), .4); m.add("pop", m.at(4, .3), .4); m.add("pdown", m.wt(4, "way fewer"), .35)
m.add("whoosh", m.mid(4, 5) - .12, .3); m.add("chime", m.wt(5, "you wouldn"), .45)
m.add("whoosh", m.wt(6, "wind"), .35); m.add("ding", m.at(7, .6), .35)
m.add("whoosh", m.mid(7, 8) - .12, .3); m.add("sting", m.wt(8, "and that"), .4)
m.add("thump", m.at(9, 0), .5); m.add("buzz", m.wt(9, "tiny"), .3); m.add("bonk", m.wt(9, "no flies"), .45)
m.write(mvol=.08, svol=.3)
