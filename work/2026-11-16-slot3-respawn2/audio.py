import sys; from shortaudio import Mix
m = Mix(sys.argv[1], 4)
m.music("tense")
m.add("static", .2, .3); m.add("pop", m.at(0, .5), .35)
m.add("whoosh", m.mid(0, 1) - .12, .3); m.steps(m.at(1, 0), 5, .28, .3); m.add("heart", m.wt(1, "two hearts"), .5)
for k, f in enumerate((.55, .72, .88)): m.add("pop", m.at(2, f), .4)
m.add("static", m.at(2, .92), .25)
m.add("whoosh", m.mid(2, 3) - .12, .3); m.add("shing", m.wt(3, "level"), .4)
m.add("chime", m.at(4, 0), .45); m.add("ding", m.wt(4, "find"), .35)
m.add("whoosh", m.mid(4, 5) - .12, .3); m.steps(m.at(5, 0), 6, .25, .2)
m.add("sting", m.wt(6, "a door"), .4); m.add("buzz", m.wt(7, "humming"), .35); m.add("buzz", m.wt(7, "humming") + .45, .3)
m.add("creak", m.at(8, .2), .35)
m.add("thump", m.at(9, 0), .5); m.add("sting", m.at(9, .3), .5)
m.add("heart", m.wt(10, "red"), .55); m.add("heart", m.wt(10, "red") + .35, .55); m.add("tbc", m.at(10, 1) + .7, .5)
m.write(mvol=.08, svol=.3)
