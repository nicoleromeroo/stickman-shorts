import sys; from shortaudio import Mix
m = Mix(sys.argv[1], 45)
m.music("mystery")
m.add("sting", .05, .4); m.ambience("wind", 0, m.L[2]["end"], .06); m.add("thump", m.wt(0, "gone."), .35)
m.add("whoosh", m.mid(0, 1) - .12, .25); m.add("pdown", m.wt(1, "she froze"), .3)
m.add("whoosh", m.mid(1, 2) - .12, .25); m.add("static", m.wt(2, "isn't"), .35); m.add("sting", m.wt(2, "anymore"), .35)
m.add("notify", m.at(3, .02), .4); m.add("notify", m.wt(3, "she's back"), .4)
m.add("whoosh", m.mid(3, 4) - .12, .2); [m.add("pop", m.wt(4, "every text") + i * .25, .25) for i in range(3)]; m.add("sting", m.wt(4, "at times"), .4)
m.add("static", m.at(5, 0), .35); m.steps(m.wt(5, "one step"), 1, .3, .4); m.add("pdown", m.wt(5, "one percent"), .4)
m.add("notify", m.at(6, .02), .4); m.add("notify", m.wt(6, "i know"), .4)
m.add("whoosh", m.mid(6, 7) - .12, .25); m.ambience("hum", m.at(7, 0), m.L[8]["end"], .05)
m.add("sting", m.wt(8, "from you"), .5); m.add("thump", m.wt(8, "nobody"), .45)
m.add("whoosh", m.mid(8, 9) - .12, .3); m.add("pop", m.at(9, .1), .35); m.add("tbc", m.L[9]["end"] + .2, .5)
m.write(mvol=.08, svol=.32)
