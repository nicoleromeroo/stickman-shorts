import sys; from shortaudio import Mix
m = Mix(sys.argv[1], 53)
m.music("upbeat")
m.add("cash", m.wt(0, "over two"), .4); m.add("pop", m.wt(0, "just for"), .3)
m.add("whoosh", m.mid(0, 1) - .12, .3)
for i in range(10): m.add("pop", m.mid(0, 1) + i * .2, .2)
m.add("ding", m.wt(1, "sixteen"), .4); m.add("whoosh", m.mid(1, 2) - .12, .3)
m.add("cash", m.wt(2, "twenty-five"), .4); m.add("bonk", m.at(3, 0), .5)
m.add("whoosh", m.mid(3, 4) - .12, .3); m.add("slide", m.wt(4, "one point"), .3); m.add("cash", m.wt(4, "fifty-two"), .4)
m.add("pop", m.at(5, .3), .35); m.add("boing", m.at(6, .1), .35); m.add("whoosh", m.mid(6, 7) - .12, .3)
m.add("pop", m.wt(7, "twenty-three"), .4); m.add("ding", m.wt(7, "about two"), .4)
m.add("whoosh", m.mid(7, 8) - .12, .3)
for i in range(12): m.add("tick", m.at(8, 0) + i * .3, .35)
m.add("whoosh", m.mid(8, 9) - .12, .3); m.add("cash", m.wt(9, "one fifty"), .35); m.add("bonk", m.wt(9, "but it's"), .45); m.add("sting", m.wt(9, "or in pain"), .4)
m.write(mvol=.08, svol=.3)
