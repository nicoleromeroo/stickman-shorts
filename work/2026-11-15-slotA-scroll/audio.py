import sys; from shortaudio import Mix
m = Mix(sys.argv[1], 47)
m.music("lofi")
for i in range(12): m.add("tick", m.at(0, 0) + i * .3, .25)
m.add("bonk", m.wt(0, "forty-seven"), .45); m.add("notify", m.wt(1, "you have school"), .35)
m.add("sting", m.at(2, 0), .45); m.add("whoosh", m.mid(2, 3) - .12, .3)
m.add("cash", m.at(3, .5), .3)
for i in range(5): m.add("pop", m.at(4, 0) + i * .33, .25)
m.add("ding", m.wt(4, "you hit"), .45); m.add("cash", m.wt(4, "you hit") + .1, .35)
m.add("boing", m.wt(5, "so your brain"), .3); m.add("whoosh", m.mid(5, 6) - .12, .3)
m.add("chime", m.wt(6, "right before"), .35); m.add("pdown", m.wt(6, "not after"), .4)
m.add("whoosh", m.mid(6, 7) - .12, .3); m.add("slide", m.at(7, .2), .3)
m.add("buzz", m.at(8, .6), .3); m.add("thump", m.at(9, 0), .55)
m.write(mvol=.08, svol=.3)
