import sys; from shortaudio import Mix
m = Mix(sys.argv[1], 8)
m.music("upbeat")
m.add("cash", .15, .4); m.add("pop", m.wt(0, "faster"), .3); m.add("boing", m.wt(0, "go on"), .35)
m.add("whoosh", m.mid(0, 1) - .12, .3); m.add("pop", m.wt(1, "avengers"), .3); m.add("ding", m.wt(1, "five days"), .35)
m.add("whoosh", m.mid(1, 2) - .12, .3); m.add("shing", m.wt(2, "three days"), .45)
m.add("whoosh", m.mid(2, 3) - .12, .3); m.add("chime", m.at(3, .05), .35); m.add("pop", m.wt(3, "the old"), .3); m.add("bonk", m.wt(3, "fifteen"), .4)
m.add("whoosh", m.mid(3, 4) - .12, .3); m.add("dingdong", m.at(4, .05), .35); m.add("pop", m.wt(4, "thirteen"), .3)
m.add("whoosh", m.mid(4, 5) - .12, .3); m.add("clink", m.at(5, .05), .35); m.add("cash", m.wt(5, "a billion"), .4); m.add("slide", m.wt(5, "twelve"), .3)
m.add("whoosh", m.mid(5, 6) - .12, .3)
for i in range(10): m.add("tick", m.at(6, 0) + i * .45, .25)
m.add("sting", m.wt(6, "forty"), .4)
m.add("whoosh", m.mid(6, 7) - .12, .3); m.add("pop", m.at(7, .1), .35); m.add("notify", m.wt(7, "comment"), .3)
m.write(mvol=.08, svol=.3)
